// Functions for arithmetic operations

function add(a, b) {
    return a + b;
}

function subtract(a, b) {
    return a - b;
}

function multiply(a, b) {
    return a * b;
}

function divide(a, b) {
    return a / b;
}

// Export all functions
module.exports = {
    add,
    subtract,
    multiply,
    divide
};